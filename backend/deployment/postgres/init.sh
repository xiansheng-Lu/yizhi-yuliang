#!/bin/sh
set -eu
# PostgreSQL官方入口以postgres执行，变量由本地忽略文件/部署机密提供。
psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=ON_ERROR_STOP=1 \
  --set=app_password="$YULIANG_APP_PASSWORD" \
  --set=auth_password="$YULIANG_AUTH_PASSWORD" \
  --set=migration_password="$YULIANG_MIGRATION_PASSWORD" <<'SQL'
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS vector;
SELECT 'CREATE ROLE app_login LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_login') \gexec
SELECT 'CREATE ROLE app_auth LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_auth') \gexec
SELECT 'CREATE ROLE app_migrate NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_migrate') \gexec
SELECT 'CREATE ROLE app_owner NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'app_owner') \gexec
SELECT 'CREATE ROLE auth_fn_owner NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE BYPASSRLS'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'auth_fn_owner') \gexec
ALTER ROLE app_login NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
ALTER ROLE app_auth NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
ALTER ROLE app_migrate NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
GRANT app_owner, auth_fn_owner TO app_migrate WITH INHERIT FALSE, SET TRUE;
ALTER ROLE app_login PASSWORD :'app_password';
ALTER ROLE app_auth PASSWORD :'auth_password';
ALTER ROLE app_migrate PASSWORD :'migration_password';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM app_migrate;
GRANT USAGE ON SCHEMA public TO app_login, app_owner, auth_fn_owner;
GRANT CREATE ON SCHEMA public TO app_owner;
CREATE SCHEMA IF NOT EXISTS auth AUTHORIZATION auth_fn_owner;
CREATE SCHEMA IF NOT EXISTS access AUTHORIZATION app_owner;
REVOKE ALL ON SCHEMA access FROM PUBLIC;
REVOKE ALL ON SCHEMA auth FROM PUBLIC;
GRANT USAGE ON SCHEMA auth TO app_auth;
ALTER DEFAULT PRIVILEGES FOR ROLE app_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE auth_fn_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
GRANT CONNECT ON DATABASE yizhi TO app_login, app_auth, app_migrate;
SQL
# 不把迁移/超级用户凭据注入业务进程；业务表对象权限由迁移按最小范围授予。
